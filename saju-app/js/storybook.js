function replaceWithJosa(text, re, to) {
  let out = ''; let last = 0;
  for (const m of text.matchAll(re)) {
    out += text.slice(last, m.index);
    const word = to(m); const restStart = m.index + m[0].length;
    const m2 = text.slice(restStart).match(JOSA_RE);
    if (m2) {
      const joined = rejoin(word, text.slice(restStart, restStart + m2[1].length + 1));
      // rejoin 결과에서 마지막 한 글자(살펴본 다음 글자)는 다시 원문에서 이어 붙임
      const tail = text.slice(restStart + m2[1].length, restStart + m2[1].length + 1);
      out += joined.slice(0, joined.length - tail.length);
      last = restStart + m2[1].length;
    } else { out += word; last = restStart; }
  }
  return out + text.slice(last);
}

/**
 * 본문을 쉬운 말로: 한자 → 한글 읽기, 오행 → 나무·불·흙·쇠·물, 사주 용어 → 쉬운 말, 「쉬운 말(쉬운 말)」 겹침 정리
 * opts.terms=false면 한자만 바꿈(부록처럼 용어를 남길 곳)
 */
export function plainText(text, opts = {}) {
  let t = String(text);
  // 「土(토)」 → 흙 / 「庚금」 → 경금 / 한자가 든 괄호(「(庚金)」·「(空亡, …)」·「(未시)」)는 지움
  t = replaceWithJosa(t, /([木火土金水])\(([목화토금수])\)/g, (m) => EL_NAME[EL_HANJA.indexOf(m[1])]);
  t = t.replace(new RegExp(`([${STEMS.join('')}])([목화토금수])`, 'g'), (m, h, e) => HANJA_KO[h] + e);
  t = t.replace(/\s?\([^()]*[\u3400-\u9fff][^()]*\)/g, '');
  // 기둥(壬寅) → 임인 · 지지 한 글자(寅) → 호랑이 · 천간 한 글자(壬) → 임 · 오행 한 글자(土) → 흙
  // 지지 두 글자(未丑 = 띠 두 개)는 「양·소」, 기둥(壬寅)은 「임인」
  t = replaceWithJosa(t, new RegExp(`[${ALL_HANJA}]{2,}`, 'g'), (m) => ([...m[0]].every((c) => BRANCHES.includes(c)) ? [...m[0]].map((c) => ANIMALS[BRANCHES.indexOf(c)]).join('·') : [...m[0]].map((c) => HANJA_KO[c]).join('')));
  t = replaceWithJosa(t, new RegExp(`[${ALL_HANJA}]`, 'g'), (m) => { const c = m[0]; const bi = BRANCHES.indexOf(c); if (bi >= 0) return opts.terms === false ? `${BRANCHES_KO[bi]}(${ANIMALS[bi]})` : ANIMALS[bi]; const ei = EL_HANJA.indexOf(c); if (ei >= 0) return EL_NAME[ei]; const si = STEMS.indexOf(c); if (si >= 0 && opts.terms !== false) return `${HANJA_KO[c]}(${EL_NAME[[0, 0, 1, 1, 2, 2, 3, 3, 4, 4][si]]})`; return HANJA_KO[c]; });
  t = t.replace(/([가-힣]+)\(\1\)/g, '$1');
  if (opts.terms !== false) {
    t = t.replace(/띠\(([가-힣]+)\) 기준 12신살로 보면/g, '$1띠에게 붙는 별로 보면');
    for (const [k, v] of PLAIN_TERMS) {
      const re = new RegExp(`(?<![가-힣])${escRe(k)}${NOT_AFTER[k] || ''}(?:\\([가-힣·\\s]{1,14}\\))?(?!격)`, 'g');
      t = replaceWithJosa(t, re, () => v);
    }
    t = t.replace(/([가-힣 ]+)\(\1\)/g, '$1');
    t = t.replace(TERM_PAREN, '');
    // 바꾼 말이 앞뒤 낱말과 겹친 곳 정리(v0.50.4): 「기운 기운」·「자리 자리」·「10년 큰 흐름(10년 큰 흐름, …)」
    t = t.replace(/(기운|자리|흐름|글자) \1/g, '$1');
    t = t.replace(/부딪힘을 이룹니다/g, '부딪힙니다').replace(/부딪힘을 이뤄요/g, '부딪혀요').replace(/부딪힘을 이루/g, '부딪히');
    t = t.replace(/아랫글자 (쥐|소|호랑이|토끼|용|뱀|말|양|원숭이|닭|개|돼지)/g, '$1 기운');
    t = t.replace(/(쥐|소|호랑이|토끼|용|뱀|말|양|원숭이|닭|개|돼지) 기운(은|는|이|가|을|를|과|와|에는|에)?/g, (m, a, j) => `${a} 기운${j ? josa('기운', ['은/는', '이/가', '을/를', '과/와'].find((p) => p.split('/').includes(j)) || j).slice(2) || j : ''}`);
    t = t.replace(/([0-9가-힣][0-9가-힣 ]{2,}?)\(\1,\s*/g, '$1(');
    t = t.replace(/([0-9가-힣][0-9가-힣 ]{2,}?)\(\1\)/g, '$1');
  }
  return t;
}

/**
 * 「그해」를 실제 연도로(v0.50.6 사용자 요청 「2027년 운세에 그해라고만 나와 헷갈린다」): 그해 → 2027년(조사도 맞춤).
 * 보는 해가 지금 해가 아니면(내년 운세를 미리 볼 때) 「올해」도 그 연도로 바꿈. 「그해·그달」(일반 설명)은 그대로
 */
export function yearize(text, Y, nowY = null) {
  if (!text || !Y) return text;
  let t = replaceWithJosa(String(text), /그해(?!·그달)/g, () => `${Y}년`);
  if (nowY != null && Number(Y) !== Number(nowY)) t = replaceWithJosa(t, /올해/g, () => `${Y}년`);
  return t.replace(new RegExp(`${Y}년 ${Y}년`, 'g'), `${Y}년`);
}

/** 리포트 전체(sections → blocks → paras·h)에 plainText 적용 */
export function plainReport(rep, opts = {}) {
  const P = (s) => (s ? plainText(s, opts) : s);
  return { ...rep, sub: P(rep.sub), sections: rep.sections.map((s) => (s.raw ? s : { ...s, h: P(s.h), intro: P(s.intro), blocks: s.blocks.map((b) => ({ ...b, h: P(b.h), paras: b.paras.map(P) })) })) };
}

/** 문장 나누기 · 비교 열쇠(띄어쓰기 무시) — 겹침 검사에 같이 씀 */
export const splitSentences = (p) => String(p || '').split(/(?<=[.!?요])\s+/).map((x) => x.trim()).filter(Boolean);
export const sentenceKey = (x) => String(x).replace(/\s+/g, '').replace(/^[^가-힣A-Za-z0-9「(]+/u, '');
/** 「이미 다른 화면에서 본 문장」 길이 기준(v0.59 4단계: 20자 이상이 같으면 같은 문장) */
export const SEED_MIN = 20;

/**
 * 문장 겹침 정리: 리포트 전체에서 이미 나온 문장은 빼기(문단이 비면 문단도, 블록이 비면 장도 뺌)
 * seed(v0.59 4단계) = 요약판에 이미 보여 준 글 — 그 안의 20자 이상 문장은 상세판에서 다시 나오지 않음
 */
export function dedupeReport(rep, seed = []) {
  const seen = new Set();
  for (const t of seed) for (const x of splitSentences(t)) { const k = sentenceKey(x); if (k.length >= SEED_MIN) seen.add(k); }
  const cut = (p) => {
    const kept = splitSentences(p).filter((x) => { const k = sentenceKey(x); if (k.length < 14) return true; if (seen.has(k)) return false; seen.add(k); return true; });
    return kept.join(' ').trim();
  };
  const sections = rep.sections.map((s) => ({ ...s, blocks: s.blocks.map((b) => ({ ...b, paras: b.paras.map(cut).filter(Boolean) })).filter((b) => b.paras.length) }))
    .filter((s) => s.appendix || s.blocks.some((b) => !b.cliff));
  return { ...rep, sections };
}
