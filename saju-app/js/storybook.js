const NOT_AFTER = { 비겁: '(?!하|한|해)', 식상: '(?!하|한|해)', 상관: '(?!없|이 ?없|하지|있)', 세운: '(?!다|\\s?(?:다짐|계획|목표|약속))', 편인: '(?!가|지|데|것|\\s?(?:하루|날|해|달|주))', 인성: '(?!격)', 일주: '(?!일|간)', 지지: '(?=\\s|에|의|는|가|와|도|$)', 충: '(?=\\(|을|이|과|\\s|$)' };
