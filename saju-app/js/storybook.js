const JOSA_PAIRS = [['이에요', '예요'], ['이었', '였'], ['이라서', '라서'], ['이라', '라'], ['이고', '고'], ['으로', '로'], ['은', '는'], ['이', '가'], ['을', '를'], ['과', '와']];
const JOSA_RE = new RegExp(`^(${JOSA_PAIRS.flat().sort((a, b) => b.length - a.length).join('|')})`);
function rejoin(word, rest) {
  const m = rest.match(JOSA_RE); if (!m) return word + rest;
  const tok = m[1]; const after = rest.slice(tok.length);
  const pair = JOSA_PAIRS.find((p) => p.includes(tok));
  // 한 글자 조사(은·이·을·과·가·는·를·와) 뒤에 한글이 바로 이어지면 다른 낱말(「이다」·「가득」 등)이라 그대로
  if (tok.length === 1 && /^[가-힣]/.test(after) && !(pair[0] === '이' && /^[다며고나니]/.test(after))) return word + rest;
  const fixed = pair[0] === '으로' ? josa(word, '으로/로') : josa(word, pair.join('/'));
  return fixed + after;
}
