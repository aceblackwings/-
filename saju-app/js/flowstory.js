/** 달 두 개를 같은 할 일끼리 묶어 한 문장으로(「10월(78점)·11월(75점)에는 …」) */
function monthsBy(list, table, g) {
  const out = [];
  for (const m of list) { const k = g(m); const o = out.find((x) => x.k === k); if (o) o.ms.push(m); else out.push({ k, ms: [m] }); }
  return out.map((o) => `${o.ms.map((m) => `${m.solarMonth}월(${m.score}점)`).join('·')}에는 ${table[o.k]}.`).join(' ');
}

/** 올해 요약(2천 자 이내): y = period.js yearOf */
export function yearStory(y) {
  const god = y.year.god; const gi = GROUP_OF[god] ?? 0; const [s1, s2] = YEAR_SHAPE[gi];
  const ms = y.months; const h1 = avg(ms.slice(0, 6).map((m) => m.score)); const h2 = avg(ms.slice(6).map((m) => m.score));
  const half = h2 - h1 >= 3 ? '뒤로 갈수록 힘이 붙는 해라, 상반기에는 준비하고 하반기에 본격적으로 움직이세요.'
    : h1 - h2 >= 3 ? '앞쪽에 힘이 더 실리는 해라, 중요한 일은 상반기 안에 시작해 두세요.'
      : '한 해 내내 고르게 흐르는 해라, 같은 속도로 꾸준히 가는 쪽이 이득이에요.';
  const SEASON = [['봄', [2, 3, 4]], ['여름', [5, 6, 7]], ['가을', [8, 9, 10]], ['겨울', [11, 12, 1]]]
    .map(([n, mm]) => ({ n, v: avg(ms.filter((m) => mm.includes(m.solarMonth)).map((m) => m.score)) }))
    .sort((a, b) => b.v - a.v);
  // 좋은 달·조심할 달은 카드 칩과 같은 값(period.js yearOf의 best·caution)을 씀 — 동점일 때도 화면끼리 어긋나지 않게
  const best = (y.best || []).slice(0, 2);
  const low = y.caution || [];
  const cats = categoryScores(y.year.score, god); const keys = Object.keys(FIELD);
  const up = keys.reduce((a, b) => (cats[b] > cats[a] ? b : a)); const dn = keys.reduce((a, b) => (cats[b] < cats[a] ? b : a));
  const D = YEAR_DO[gi]; const g = (m) => GROUP_OF[m.god] ?? 0;
  const paras = [
    `${y.sajuYear}년은 ${josa(PLAIN_GOD[god], '이/가')} 앞에서 이끄는 해이고, 한 해 점수는 ${y.year.score}점이에요. ${s1} ${s2}`,
    `상반기(입춘부터 여섯 달) 평균은 ${h1}점, 하반기는 ${h2}점이에요. ${half}`,
    `계절로 보면 ${SEASON[0].n}(${SEASON[0].v}점)이 가장 힘차고, ${SEASON[3].n}(${SEASON[3].v}점)은 속도를 늦추는 계절이에요.`,
    `🌟 힘이 실리는 달: ${monthsBy(best, MONTH_DO, g)}`,
    `🍵 쉬어 갈 달: ${monthsBy(low, MONTH_SLOW, g)}`,
    `분야로 보면 ${FIELD[up]}(${cats[up]}점)에 가장 힘이 실려요. ${FIELD_UP[up]} ${josa(FIELD[dn], '은/는').replace(/(은|는)$/, `(${cats[dn]}점)$1`)} 아껴 쓰는 분야예요. ${FIELD_LOW[dn]}`,
    `✅ 올해 할 일: ① ${D[0]} ② ${D[1]} ③ ${D[2]}.`,
    `⛔ 올해 피할 일: ${YEAR_AVOID[gi]}.`,
    ...(y.daewoon ? [`올해 점수에는 지금 지나는 10년의 흐름(${y.daewoon.score}점)이 30%만큼 함께 들어 있어요. 그래서 같은 해라도 사람마다 느낌이 달라요.`] : []),
    '연말에는 올해 잘한 일 세 가지를 적어 두세요. 다음 해 계획을 세울 때 가장 좋은 출발점이 돼요.',
  ];
  return { head: paras[0], paras };
}

