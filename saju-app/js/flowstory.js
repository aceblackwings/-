/**
 * 10년 요약(3천 자 이내)
 * dw = luck.js computeDaewoon, cur = 지금 대운 기둥, age = 지금 나이, godOf(p) = 대운 기둥의 십신
 */
export function decadeStory({ dw, cur, age, godOf, name = '' }) {
  const who = name ? `${name} 님` : '당신';
  if (!dw || !cur) {
    const start = dw?.startAge ?? 0;
    const paras = [`${josa(who, '은/는')} 아직 첫 10년 흐름이 시작되기 전이에요. 첫 흐름은 ${start}세부터 시작돼요.`, '그 전까지는 타고난 바탕대로 자라는 시기라, 좋아하는 것을 많이 해 보고 몸을 튼튼히 하는 것이 가장 좋은 준비예요.'];
    return { head: paras[0], paras };
  }
  const list = dw.pillars; const i = list.findIndex((p) => p.startAge === cur.startAge);
  const prev = i > 0 ? list[i - 1] : null; const next = list[i + 1] || null;
  const god = godOf(cur); const gi = GROUP_OF[god] ?? 0; const [a, b, c] = DECADE_SHAPE[gi];
  const year = Math.max(1, Math.min(10, age - cur.startAge + 1));
  const phase = year <= 3 ? '흐름이 바뀐 지 얼마 되지 않아, 새 흐름에 몸과 생활을 맞추는 때예요. 큰 결정은 1~2년 지켜본 뒤에 해도 늦지 않아요.'
    : year <= 7 ? '흐름의 한가운데라, 이 10년의 장점이 가장 또렷하게 드러나는 때예요. 미뤄 둔 목표는 지금 꺼내세요.'
      : '흐름의 끝자락이라, 이 10년에 얻은 것을 정리하고 다음 흐름을 준비하는 때예요.';
  const D = DECADE_DO[gi];
  const top = [...list].sort((x, y) => y.score - x.score).slice(0, 2).sort((x, y) => x.startAge - y.startAge);
  const paras = [
    `지금 ${josa(who, '은/는')} ${cur.startAge}~${cur.endAge}세, ${josa(PLAIN_GOD[god], '이/가')} 흐르는 10년을 지나고 있어요(점수 ${cur.score}점). ${a}`,
    `${b} ${c}`,
    `올해는 이 10년 가운데 ${year}년째예요. ${phase}`,
    ...(prev ? [`지난 10년(${prev.startAge}~${prev.endAge}세, ${prev.score}점)과 비교하면 ${cur.score > prev.score + 2 ? `${cur.score - prev.score}점 올라, 예전보다 일이 덜 막히고 손에 남는 것이 많아지는 흐름이에요.` : cur.score < prev.score - 2 ? `${prev.score - cur.score}점 내려, 넓히기보다 다지는 데 힘을 쓰면 좋은 흐름이에요.` : '점수가 비슷해, 하던 일을 이어 가며 방향만 다듬으면 되는 흐름이에요.'}`] : []),
    (AGE_LINE.find(([n]) => age <= n) || AGE_LINE[3])[1],
    `✅ 이 10년의 할 일: ① ${D[0]} ② ${D[1]} ③ ${D[2]}.`,
    `⛔ 이 10년의 피할 일: ${DECADE_AVOID[gi]}.`,
    ...(next ? [`${next.startAge}세부터는 ${josa(PLAIN_GOD[godOf(next)], '이/가')} 들어오는 새 10년이에요(점수 ${next.score}점, 앞으로 ${Math.max(0, next.startAge - age)}년 뒤). ${NEXT_PREP[GROUP_OF[godOf(next)] ?? 0]}`] : []),
    `평생 흐름 가운데 점수가 가장 높은 두 시기는 ${top[0].startAge}~${top[0].endAge}세(${top[0].score}점)와 ${top[1].startAge}~${top[1].endAge}세(${top[1].score}점)예요.${top.some((p) => p.startAge === cur.startAge) ? ' 지금이 바로 그 시기 가운데 하나예요.' : ''}`,
    `🎯 이 10년의 목표: ${DECADE_GOAL[gi]}.`,
  ];
  return { head: paras[0], paras };
}
