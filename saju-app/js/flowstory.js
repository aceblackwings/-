/** 이번 주 요약(1천 자 이내) */
export function weekStory(w) {
  const g = (d) => GROUP_OF[d.god] ?? 0;
  const band = w.avg >= 75 ? '힘이 넉넉하게 실린 한 주' : w.avg >= 65 ? '고르게 흘러가는 한 주' : '숨을 고르며 차분히 가는 한 주';
  const first = avg(w.days.slice(0, 3).map((x) => x.score)); const last = avg(w.days.slice(4).map((x) => x.score));
  const shape = last - first >= 4 ? '주 후반으로 갈수록 힘이 붙으니, 중요한 일은 목요일 뒤로 잡으면 좋아요.'
    : first - last >= 4 ? '주 초반에 힘이 더 실리니, 중요한 일은 월요일부터 수요일 사이에 끝내 두세요.'
      : '요일마다 큰 차이 없이 흘러가니, 한 번에 몰아서 하기보다 날마다 조금씩 나눠 하세요.';
  const top = (k) => w.days.reduce((a, b) => (b.scores[k] > a.scores[k] ? b : a));
  const cnt = [0, 0, 0, 0, 0]; w.days.forEach((d) => { cnt[g(d)] += d.score; });
  const main = cnt.indexOf(Math.max(...cnt));
  const D = WEEK_DO[main];
  return {
    head: `이번 주는 평균 ${w.avg}점으로, ${band}예요.`,
    paras: [
      `이번 주는 평균 ${w.avg}점으로, ${band}예요. ${shape}`,
      `가장 힘이 실리는 날은 ${dayText(w.best.date)}(${w.best.score}점)이에요. ${WEEK_BEST[g(w.best)]}`,
      `가장 조심스러운 날은 ${dayText(w.worst.date)}(${w.worst.score}점)이에요. ${WEEK_LOW[g(w.worst)]}`,
      `분야별로 보면 돈 일은 ${dowOf(top('wealth').date)}요일, 사람 만남은 ${dowOf(top('social').date)}요일, 일·공부는 ${dowOf(top('career').date)}요일에 맞추면 같은 노력으로 더 크게 돌아와요.`,
      `✅ 이번 주 할 일: ① ${D[0]} ② ${D[1]} ③ ${D[2]}.`,
      `⛔ 이번 주 피할 일: ${WEEK_AVOID[main]}.`,
      '일요일 저녁에 할 일 세 가지 가운데 몇 개를 지켰는지 세어 보세요. 하나만 지켜도 다음 주가 한결 가벼워져요.',
    ],
  };
}

