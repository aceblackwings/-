/** 자기 호칭 + 주격 조사: 나 → 내가, 저 → 제가 */
export const meSubject = (me) => (me === '나' ? '내가' : me === '저' ? '제가' : `${me}가`);

// 자리표시자 뒤 조사는 넣는 말의 받침에 맞춤({friend}랑은 → 용이랑은, 토끼랑은)
const JOSA_PAIR = { 랑: '이랑/랑', 은: '은/는', 는: '은/는', 이: '이/가', 가: '이/가', 을: '을/를', 를: '을/를', 과: '과/와', 와: '과/와' };
const fill = (s, vars = {}) => s.replace(/\{(\w+)\}(랑|은|는|이|가|을|를|과|와)?/g, (_, k, j) => { const v = String(vars[k] ?? ''); return j && v ? josa(v, JOSA_PAIR[j]) : v + (j || ''); });

/** 진화 단계에 따라 말투가 자란다: 1단계는 문장 앞에 아기(🍼), 5단계부터 끝에 위엄(✦) */
function stageVoice(text, stage) {
  if (stage === 1) return `🍼 ${text}`;
  if (stage >= 5) return `${text} ✦`;
  return text;
}

export function personalityOf(zodiacIndex) {
  return PERSONALITIES[zodiacIndex];
}

/**
 * 상황별 대사
 * @param zodiacIndex 연지(0~11)
 * @param situation 'greet'|'tier'|'best'|'mission'|'missionDone'|'equip'|'evolve'|'tap'|'back'|'compat'
 * @param opts {stage, vars, index, tier, seed}
 */
export function speak(zodiacIndex, situation, opts = {}) {
  const p = PERSONALITIES[zodiacIndex];
  let line = p[situation];
  if (Array.isArray(line)) {
    let i = opts.index;
    if (situation === 'tier') i = opts.tier ?? 1;
    if (i === undefined) i = Math.floor((opts.seed ?? Math.random()) * line.length);
    line = line[Math.max(0, Math.min(line.length - 1, i))];
  }
  return stageVoice(fill(line, opts.vars), opts.stage || 2);
}
